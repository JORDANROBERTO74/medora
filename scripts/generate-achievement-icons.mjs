// Regenerates the achievement icons from Fluent Emoji Flat (Microsoft, MIT).
// Run with: node scripts/generate-achievement-icons.mjs
// Iconify only supplies the icon bodies; the app renders them inline, so no API
// call happens at runtime.
import fs from 'node:fs'
import path from 'node:path'

const ICONS = [
  'seedling',
  'books',
  'open-book',
  'fire',
  'high-voltage',
  'rocket',
  'sparkles',
  'bullseye',
  'gem-stone',
  'stethoscope',
  'brain',
  'military-medal',
  'pencil',
  'memo',
  'crown',
  'trophy',
  '1st-place-medal',
]

const response = await fetch(
  `https://api.iconify.design/fluent-emoji-flat.json?icons=${ICONS.join(',')}`
)
if (!response.ok) {
  throw new Error(`Iconify responded ${response.status}`)
}
const collection = await response.json()

const missing = ICONS.filter((id) => !collection.icons?.[id])
if (missing.length > 0) {
  throw new Error(`Icons not found: ${missing.join(', ')}`)
}

const entries = ICONS.map((id) => {
  const body = collection.icons[id].body
  if (/[<>&]/.test(body) === false) throw new Error(`Unexpected body for ${id}`)
  return `  '${id}': ${JSON.stringify(body)},`
}).join('\n')

const file = `// Generated by scripts/generate-achievement-icons.mjs — do not edit by hand.
// Source: Fluent Emoji Flat (Microsoft), MIT license, served by Iconify.
export const achievementIconBodies = {
${entries}
} as const

export type AchievementIconKey = keyof typeof achievementIconBodies
`

const target = path.join('src', 'lib', 'achievements', 'icon-data.ts')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, file)
console.log(`Wrote ${target} with ${ICONS.length} icons`)
